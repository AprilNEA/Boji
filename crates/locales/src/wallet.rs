//! Renders the copy of the Apple Wallet pass that `bizserver/` signs.
//!
//! Wallet localizes a pass with a `pass.strings` file in each `<language>.lproj`
//! directory of the pass archive. The server builds those files for each pass,
//! so the generator writes a Rust table instead of the files themselves.
//!
//! `pass.json` holds the fallback text of each string, and every `pass.strings`
//! maps that text to the text of its language. The fallback text is therefore
//! the localization key, and [`crate::validate`] requires it to be unique. A
//! device whose language has no `.lproj` directory shows the fallback text.

use crate::message::{Forms, Message, Segment};
use crate::model::Target;
use crate::validate::{ValidEntry, Validated};

/// The generated file, relative to the repository root.
pub const PATH: &str = "bizserver/src/wallet/strings.rs";

/// Renders the table of every key for the `wallet` target.
pub fn render(validated: &Validated<'_>) -> String {
    let config = validated.config;
    let languages: Vec<_> = std::iter::once(&config.fallback)
        .chain(
            config
                .release
                .iter()
                .filter(|locale| **locale != config.fallback),
        )
        .collect();
    let count = languages.len();
    let entries: Vec<_> = validated.entries_for(Target::Wallet).collect();

    let mut out = String::from(
        "//! Generated by crates/locales from locales/. Do not edit this file.\n\
         //!\n\
         //! The copy of the Apple Wallet pass. `pass.json` holds the fallback text, and\n\
         //! the `pass.strings` file of each language maps it to the text of that language.\n\
         \n",
    );
    out.push_str(
        "/// The `.lproj` directory names of the pass. The fallback language comes first.\n",
    );
    let names: Vec<String> = languages
        .iter()
        .map(|locale| format!("{:?}", locale.as_str()))
        .collect();
    out.push_str(&format!(
        "pub(crate) const LANGUAGES: [&str; {count}] = [{}];\n\n",
        names.join(", ")
    ));
    out.push_str(&format!(
        "/// One string of the pass in every language of [`LANGUAGES`].\n\
         pub(crate) struct Text {{\n\
         \x20   /// The text in each language of [`LANGUAGES`], in the same order.\n\
         \x20   pub(crate) values: [&'static str; {count}],\n\
         }}\n\n\
         impl Text {{\n\
         \x20   /// The fallback text. `pass.json` holds it, and it is the localization key.\n\
         \x20   pub(crate) const fn key(&self) -> &'static str {{\n\
         \x20       self.values[0]\n\
         \x20   }}\n\
         }}\n"
    ));
    for entry in &entries {
        render_entry(&mut out, entry, &languages);
    }
    out.push_str(&format!(
        "\n/// Every string of the pass, in the order of `locales/meta/`.\n\
         pub(crate) const ALL: [&Text; {}] = [\n",
        entries.len()
    ));
    for entry in &entries {
        out.push_str(&format!("    &{},\n", const_name(entry)));
    }
    out.push_str("];\n");
    out
}

fn render_entry(out: &mut String, entry: &ValidEntry<'_>, languages: &[&crate::Locale]) {
    out.push('\n');
    let comment = entry
        .meta
        .comment
        .as_deref()
        .map(str::trim)
        .unwrap_or_default();
    let mut lines = comment.lines().map(str::trim);
    match lines.next() {
        Some(first) => out.push_str(&format!("/// `{}`: {first}\n", entry.key)),
        None => out.push_str(&format!("/// `{}`.\n", entry.key)),
    }
    for line in lines {
        if line.is_empty() {
            out.push_str("///\n");
        } else {
            out.push_str(&format!("/// {line}\n"));
        }
    }
    out.push_str(&format!(
        "pub(crate) const {}: Text = Text {{\n    values: [\n",
        const_name(entry)
    ));
    for locale in languages {
        let message = entry
            .messages
            .get(locale)
            .expect("validation requires every release language");
        let text = literal_text(message).expect("validation rejects arguments for wallet keys");
        out.push_str(&format!("        {text:?},\n"));
    }
    out.push_str("    ],\n};\n");
}

/// The Rust constant of a key: `wallet_label_nickname` becomes `WALLET_LABEL_NICKNAME`.
fn const_name(entry: &ValidEntry<'_>) -> String {
    entry.key.as_str().to_ascii_uppercase()
}

/// The text of a message that has no arguments and no plural, or `None`.
///
/// A `pass.strings` value has no format arguments, so [`crate::validate`]
/// accepts only such messages for the `wallet` target.
pub(crate) fn literal_text(message: &Message) -> Option<String> {
    let Forms::Single(segments) = message.forms() else {
        return None;
    };
    let mut text = String::new();
    for segment in &segments {
        match segment {
            Segment::Text(literal) => text.push_str(literal),
            Segment::Arg(_) | Segment::Count(_) => return None,
        }
    }
    Some(text)
}
